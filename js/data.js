const LAW_NAMES = Object.keys(LAW_DATA);

// 지정한 법령(또는 전체)에서 조문 목록을 평탄화해서 반환
function getArticlePool(lawName) {
  if (!lawName || lawName === "전체") {
    return LAW_NAMES.flatMap((name) =>
      LAW_DATA[name].map((a) => ({ ...a, law: name }))
    );
  }
  return (LAW_DATA[lawName] || []).map((a) => ({ ...a, law: lawName }));
}

function shuffleArray(arr) {
  const copy = arr.slice();
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}
